int TMR_getAndSetFlag(Ifx_TickTime *cnt,  uint32 tmr, uint32 mode)
{

    uint8   r=1;

    /* BSP */
    if(isDeadLine(*cnt) )
    {
//        bspTime = getDeadLine(ms * TimeConst[TIMER_INDEX_1MS] );
        *cnt = getDeadLine(tmr * TimeConst[mode] );
        r=0;
    }

    return r;
}

